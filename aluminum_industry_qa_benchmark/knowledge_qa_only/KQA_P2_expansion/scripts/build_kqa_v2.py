def record(qid, q, answer, points, domain, typ, difficulty, sid, evidence, conditions, family, unit, reasoning, concepts, pitfalls, status="Evidence-Verified", inference="无"):
    title, year, loc, page = SOURCES[sid]
    return {
        "question_id": qid, "question": q, "reference_answer": answer,
        "key_answer_points": points, "explanation": "；".join(points),
        "required_concepts": concepts, "knowledge_domain": domain,
        "question_type": typ, "reasoning_type": reasoning, "difficulty": difficulty,
        "applicability": conditions, "applicable_conditions": conditions,
        "source_ids": [sid], "source_group": "现代铝电解_2008",
        "evidence_locations": [f"{loc}，{page}"], "evidence_excerpt": evidence,
        "source_metadata": {"source_id": sid, "title": title, "year_or_version": year, "location": loc, "page": page, "verified_from_page_image": True},
        "knowledge_unit_id": unit, "question_family_id": family,
        "common_incorrect_conclusions": pitfalls,
        "inference_component": inference, "evidence_status": status,
        "review_status": "Candidate", "expert_review_status": "Pending external domain-expert review",
    }

