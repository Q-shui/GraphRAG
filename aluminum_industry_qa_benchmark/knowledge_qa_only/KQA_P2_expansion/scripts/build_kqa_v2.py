def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = load_old() + NEW
    assert len(rows) == 33 and len({x['question_id'] for x in rows}) == 33
    for r in rows:
        forbidden = ("根据教材", "教材指出", "如图所示", "根据上述", "根据某篇论文", "作者认为")
        assert not any(x in r["question"] for x in forbidden), r["question_id"]
    text = "\n".join(json.dumps(x, ensure_ascii=False) for x in rows) + "\n"
    (OUT / "knowledge_qa_v2_candidates.jsonl").write_text(text, encoding="utf-8")
    benchmark = [x for x in rows if x["evidence_status"] == "Evidence-Verified"]
    (OUT / "knowledge_qa_benchmark_view.jsonl").write_text("\n".join(json.dumps(x, ensure_ascii=False) for x in benchmark)+"\n", encoding="utf-8")
    audit = [{k: x.get(k) for k in ("question_id","origin","old_question","question","knowledge_unit_id","question_family_id","source_ids","evidence_locations","evidence_status","inference_component","applicability","review_status","expert_review_status","common_incorrect_conclusions")} for x in rows]
    (OUT / "knowledge_qa_audit_view.jsonl").write_text("\n".join(json.dumps(x, ensure_ascii=False) for x in audit)+"\n", encoding="utf-8")
    print(json.dumps({"old_reverified": 13, "new": len(NEW), "total": len(rows), "benchmark_view": len(benchmark)}, ensure_ascii=False))

if __name__ == "__main__": main()
